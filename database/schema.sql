-- ---------------------------------------------------------------------
-- Cuestionario: la fecha de actualización se pone sola al editarlo.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_cuestionario_fecha_actualizacion()
RETURNS trigger AS $$
BEGIN
    NEW.fecha_actualizacion := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_cuestionario_fecha_actualizacion
BEFORE UPDATE
ON CUESTIONARIO
FOR EACH ROW
EXECUTE FUNCTION fn_cuestionario_fecha_actualizacion();

-- ---------------------------------------------------------------------
-- Cuestionario: Al borrar un solicitante se borra también su cuestionario
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_solicitante_borra_cuestionario()
RETURNS trigger AS $$
BEGIN
    DELETE FROM cuestionario
	WHERE id_cuestionario = OLD.id_cuestionario;
    
	RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_solicitante_borra_cuestionario
AFTER DELETE 
ON SOLICITANTE
FOR EACH ROW 
EXECUTE FUNCTION fn_solicitante_borra_cuestionario();

-- ---------------------------------------------------------------------
-- Animal: Un animal no puede estar a la vez en dos subtipos
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_animal_subtipo_unico()
RETURNS trigger AS $$
BEGIN
    IF (TG_TABLE_NAME <> 'perro'   AND EXISTS (SELECT 1 FROM perro   WHERE id_animal = NEW.id_animal))
    OR (TG_TABLE_NAME <> 'gato'    AND EXISTS (SELECT 1 FROM gato    WHERE id_animal = NEW.id_animal))
    OR (TG_TABLE_NAME <> 'exotico' AND EXISTS (SELECT 1 FROM exotico WHERE id_animal = NEW.id_animal))
    THEN
        RAISE EXCEPTION 'El animal % ya pertenece a otro subtipo', NEW.id_animal;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_perro_subtipo_unico
BEFORE INSERT 
ON PERRO
FOR EACH ROW 
EXECUTE FUNCTION fn_animal_subtipo_unico();

CREATE TRIGGER trg_gato_subtipo_unico
BEFORE INSERT 
ON GATO
FOR EACH ROW 
EXECUTE FUNCTION fn_animal_subtipo_unico();

CREATE TRIGGER trg_exotico_subtipo_unico
BEFORE INSERT 
ON EXOTICO
FOR EACH ROW 
EXECUTE FUNCTION fn_animal_subtipo_unico();

-- ---------------------------------------------------------------------
-- Animal: Todo animal tiene que tener fila en uno de los subtipos. 
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_animal_tiene_subtipo()
RETURNS trigger AS $$
BEGIN
    IF NOT (EXISTS (SELECT 1 FROM perro   WHERE id_animal = NEW.id_animal)
         OR EXISTS (SELECT 1 FROM gato    WHERE id_animal = NEW.id_animal)
         OR EXISTS (SELECT 1 FROM exotico WHERE id_animal = NEW.id_animal))
    THEN
        RAISE EXCEPTION 'El animal % debe ser perro, gato o exotico', NEW.id_animal;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_animal_tiene_subtipo
AFTER INSERT 
ON ANIMAL
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW 
EXECUTE FUNCTION fn_animal_tiene_subtipo();



